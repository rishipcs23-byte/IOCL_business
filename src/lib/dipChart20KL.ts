/**
 * Get exact chart calculated stock in litres for a given dip reading in cm.
 * Chart steps are in 0.2 cm increments.
 * If dip reading exact match is found in chart, return it.
 * If reading falls between 0.2 cm steps, return linearly interpolated volume rounded to whole litres.
 */
export function getChartCalculatedStock(dipCm: number): number {
  if (isNaN(dipCm) || dipCm <= 0) return 0;
  
  const clampedDip = Math.min(Math.max(0, dipCm), 211.0);
  const formattedKey = clampedDip.toFixed(1);
  
  if (DIP_CHART_20KL[formattedKey] !== undefined) {
    return DIP_CHART_20KL[formattedKey];
  }

  const lowerStep = (Math.floor(clampedDip * 5) / 5).toFixed(1);
  const upperStep = (Math.ceil(clampedDip * 5) / 5).toFixed(1);

  const lowerVol = DIP_CHART_20KL[lowerStep] ?? 0;
  const upperVol = DIP_CHART_20KL[upperStep] ?? lowerVol;

  if (lowerStep === upperStep || lowerVol === upperVol) {
    return lowerVol;
  }

  const fraction = (clampedDip - parseFloat(lowerStep)) / 0.2;
  return Math.round(lowerVol + fraction * (upperVol - lowerVol));
}
